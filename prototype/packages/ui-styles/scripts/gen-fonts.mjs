#!/usr/bin/env node

// Vendors the IBM Plex Sans Var subsets into src/fonts/ and regenerates
// src/globals/font-fallbacks.generated.css, both from the pinned @ibm/plex-sans-variable.

import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { entireMetricsCollection } from '@capsizecss/metrics/entireMetricsCollection';
import { fromBuffer } from '@capsizecss/unpack';
import { fromFile } from '@capsizecss/unpack/fs';

const here = dirname(fileURLToPath(import.meta.url));
const FONTS_DIR = resolve(here, '../src/fonts');
const OUT_FILE = resolve(here, '../src/globals/font-fallbacks.generated.css');
const PLEX_VAR_DIR = dirname(fileURLToPath(import.meta.resolve('@ibm/plex-sans-variable/package.json')));

const PLEX_VAR_SUBSETS = ['Latin1', 'Latin2', 'Pi', 'Cyrillic'];

const SANS = {
  fallbackName: 'Reinforce Sans Fallback',
  fallback: lookup('Arial'),
  weights: [400, 500, 600, 700],
  stretches: [85, 100],
  source: `${PLEX_VAR_DIR}/fonts/complete/ttf/IBM Plex Sans Var-Roman.ttf`,
};

const MONO = {
  fallbackName: 'IBM Plex Mono Fallback',
  fallback: lookup('Courier New'),
  weights: [400, 500, 600],
  filePrefix: 'ibm-plex-mono',
};

function lookup(name) {
  const metrics = Object.values(entireMetricsCollection).find((m) => m.familyName === name);
  if (!metrics) throw new Error(`No capsize metrics for fallback "${name}".`);
  return metrics;
}

function calc(primary, fb) {
  // Chrome fallback formula — both ratios normalized by their own unitsPerEm before dividing.
  // Skipping UPM normalization mis-scales across fonts with different em squares (e.g. Plex 1000, Arial 2048).
  const primaryRatio = primary.xWidthAvg / primary.unitsPerEm;
  const fbRatio = fb.xWidthAvg / fb.unitsPerEm;
  const sizeAdjust = primaryRatio / fbRatio;
  const scaled = primary.unitsPerEm * sizeAdjust;
  const pct = (n) => `${((n / scaled) * 100).toFixed(4)}%`;
  return {
    sizeAdjust: `${(sizeAdjust * 100).toFixed(4)}%`,
    ascent: pct(primary.ascent),
    descent: pct(Math.abs(primary.descent)),
    lineGap: pct(primary.lineGap),
  };
}

function fallbackFace({ fallbackName, fallback }, primary, weight, stretch) {
  const { sizeAdjust, ascent, descent, lineGap } = calc(primary, fallback);
  return [
    `@font-face {`,
    `  font-family: "${fallbackName}";`,
    `  src: local("${fallback.familyName}");`,
    `  font-weight: ${weight};`,
    ...(stretch ? [`  font-stretch: ${stretch}%;`] : []),
    `  font-style: normal;`,
    `  size-adjust: ${sizeAdjust};`,
    `  ascent-override: ${ascent};`,
    `  descent-override: ${descent};`,
    `  line-gap-override: ${lineGap};`,
    `}`,
    '',
  ];
}

async function vendorPlexVarSubsets() {
  for (const subset of PLEX_VAR_SUBSETS) {
    await copyFile(
      `${PLEX_VAR_DIR}/fonts/split/woff2/IBM Plex Sans Var-Roman-${subset}.woff2`,
      `${FONTS_DIR}/ibm-plex-sans-var-${subset.toLowerCase()}.woff2`,
    );
  }
}

async function sansFaces() {
  const buffer = await readFile(SANS.source);
  const upright = await fromBuffer(buffer);
  const blocks = [];
  for (const stretch of SANS.stretches) {
    for (const weight of SANS.weights) {
      // constraint: capsize forwards `postscriptName` to fontkitten's getFont, which also takes axis settings.
      const instance = await fromBuffer(buffer, {
        postscriptName: { wght: weight, wdth: stretch },
      });
      if (stretch !== 100 && instance.xWidthAvg === upright.xWidthAvg) {
        throw new Error(`capsize ignored the wdth ${stretch} instance of ${SANS.source}.`);
      }
      blocks.push(...fallbackFace(SANS, instance, weight, stretch));
    }
  }
  return blocks;
}

async function monoFaces() {
  const blocks = [];
  for (const weight of MONO.weights) {
    const primary = await fromFile(`${FONTS_DIR}/${MONO.filePrefix}-${weight}-latin.woff2`);
    blocks.push(...fallbackFace(MONO, primary, weight));
  }
  return blocks;
}

async function main() {
  await vendorPlexVarSubsets();
  const blocks = [
    `/* Auto-generated by scripts/gen-fonts.mjs — do not edit by hand. */`,
    `/* Metric-overridden fallbacks neutralize CLS during font swap (Chrome font-fallbacks doctrine). */`,
    '',
    ...(await sansFaces()),
    ...(await monoFaces()),
  ];
  await writeFile(OUT_FILE, blocks.join('\n'), 'utf8');
  console.log(`wrote ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
